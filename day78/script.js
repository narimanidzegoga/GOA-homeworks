// 1) დაწერეთ ფუნქცია, რომელიც მიიღებს ადამიანის სახელს და დააბრუნებს ტექსტს:
// "გამარჯობა, ნიკა!"
// სახელი უნდა იყოს გადაცემული არგუმენტით.

function sayHello(name) {
    return "გამარჯობა, " + name
}

// 2) დაწერეთ ფუნქცია, რომელიც მიიღებს დაბადების წელს და მიმდინარე წელს და გამოთვლის ადამიანის ასაკს.

function age(year_born, current_year){
    let age = current_year - year_born
    return age
}

// 3) დაწერეთ ფუნქცია, რომელიც მიიღებს სამ რიცხვს და დააბრუნებს მათ საშუალო არითმეტიკულს.
function average(num1, num2, num3) {
    return (num1 + num2 + num3) / 3
}

// 4) დაწერეთ ფუნქცია, რომელიც მიიღებს პროდუქტის ფასსა და ფასდაკლების პროცენტს და დააბრუნებს საბოლოო ფასს.
function finalPrice(price, discount) {
    return price - (price * discount / 100)
}

// 5) დადებითი და უარყოფითი რიცხვი

// დაწერეთ ფუნქცია, რომელიც მიიღებს რიცხვს და დააბრუნებს:
// "დადებითი" — თუ რიცხვი ნულზე მეტია.
// "უარყოფითი" — თუ რიცხვი ნულზე ნაკლებია.
// "ნულის ტოლია" — თუ რიცხვი ნულის ტოლია.
function positive_ornot(num) {
    if (num > 0) {
        return "დადებითი"
    } else if (num < 0) {
        return "უარყოფითი"
    } else {
        return "ნულის ტოლია"
    }
}

// 6) დაწერეთ ფუნქცია, რომელიც მიიღებს რიცხვს და დაადგენს, არის თუ არა ის ლუწი ან კენტი.
function odd_or_even(num) {
    if (num % 2 === 0) {
        return "ლუწი"
    } else {
        return "კენტი"
    }
}

// 7) დაწერეთ ფუნქცია, რომელიც მიიღებს ტემპერატურას:
// 30-ზე მეტი — "ცხელა".
// 15-დან 30-მდე — "თბილა".
// 15-ზე ნაკლები — "ცივა".

function checktemperature(temp) {
    if (temp > 30) {
        return "ცხელა"
    } else if (temp >= 15) {
        return "თბილა"
    } else {
        return "ცივა"
    }
}

// 8) დაწერეთ ფუნქცია, რომელიც მიიღებს პაროლს:
// თუ პაროლი უდრის "javascript123"-ს, დააბრუნოს "სწორი პაროლი".
// სხვა შემთხვევაში დააბრუნოს "არასწორი პაროლი".
function checkpassword(password) {
    if (password === "javascript123") {
        return "სწორი პაროლი"
    } else {
        return "არასწორი პაროლი"
    }
}

// 9) დაწერეთ ფუნქცია, რომელიც მიიღებს თანამშრომლის ხელფასს:
// თუ ხელფასი 2000 ლარზე ნაკლებია, დაუმატოს 20% ბონუსი.
// სხვა შემთხვევაში დაუმატოს 10% ბონუსი.
function bonus(salary) {
    if (salary < 2000) {
        return salary * 1.2
    } else {
        return salary * 1.1
    }
}

